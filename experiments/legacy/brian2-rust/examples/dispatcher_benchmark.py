def parse_levels(value):
    try:
        levels = sorted(set(int(item) for item in value.split(",")))
    except ValueError as error:
        raise argparse.ArgumentTypeError(
            "levels must be comma-separated integers") from error
    if not levels or levels[0] != 1 or levels[-1] > 256:
        raise argparse.ArgumentTypeError(
            "levels must include 1 and stay within 1..256")
    return levels


def digest(path):
    result = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024*1024), b""):
            result.update(chunk)
    return result.hexdigest()


def build(workload, output):
    definition = WORKLOADS[workload]
    build_output = output / "build"
    if not definition["creates_output"]:
        build_output.mkdir()
    environment = {**os.environ, **PINNED_ENVIRONMENT, "B2_NUM_THREADS": "1"}
    subprocess.run([
        sys.executable, str(HERE / definition["script"]),
        "--backend", "aot", "--output", str(build_output), "--threads", "1",
        *definition["arguments"],
    ], cwd=ROOT, env=environment, check=True, timeout=900,
       stdout=subprocess.DEVNULL)
    current = build_output / "project/native"
    legacy = output / "legacy"
    shutil.copytree(current, legacy)
    source_path = legacy / "main.rs"
    source = source_path.read_text()
    start = source.index("#[repr(align(64))]\nstruct WorkerSignal")
    end = source.index("fn check(ok: bool", start)
    source_path.write_text(source[:start] + LEGACY_DISPATCHER + source[end:])
    subprocess.run([
        "rustc", "--edition=2021", "-C", "opt-level=3",
        "-C", "codegen-units=1", "-C", "panic=abort", source_path,
        "-o", legacy / "b2-native",
    ], check=True, timeout=300)
    return {
        "idle-parking": current / "b2-native",
        "shared-counter": legacy / "b2-native",
    }, current / "instance.bin"


def run(binary, instance, threads, replays):
    environment = {**os.environ, **PINNED_ENVIRONMENT,
                   "B2_NUM_THREADS": str(threads)}
    with tempfile.TemporaryDirectory(prefix="b2-dispatcher-") as temporary:
        elapsed = 0.0
        result_hash = None
        for replay in range(replays):
            output = Path(temporary) / f"results-{replay}"
            subprocess.run([binary, instance, output], env=environment, check=True,
                           stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
                           text=True, timeout=300)
            summary = json.loads((output / "summary.json").read_text())
            elapsed += summary["timings"]["simulation_and_recording_seconds"]
            value = digest(output / "results.bin")
            result_hash = result_hash or value
            if value != result_hash:
                raise AssertionError("replays produced different result dumps")
        return elapsed, result_hash


def measure(workload, output, levels, repeats):
    output.mkdir()
    binaries, instance = build(workload, output)
    replays = WORKLOADS[workload]["replays_per_sample"]
    samples = {
        str(level): {variant: [] for variant in binaries} for level in levels
    }
    paired_speedups = {str(level): [] for level in levels}
    reference_hash = None
    for level in levels:
        for variant, binary in binaries.items():
            _, value = run(binary, instance, level, replays)
            reference_hash = reference_hash or value
            if value != reference_hash:
                raise AssertionError("dispatcher variant changed the result dump")
    for repeat in range(repeats):
        level_order = levels[repeat % len(levels):] + levels[:repeat % len(levels)]
        for level in level_order:
            order = (("shared-counter", "idle-parking", "idle-parking",
                      "shared-counter") if repeat % 2 == 0 else
                     ("idle-parking", "shared-counter", "shared-counter",
                      "idle-parking"))
            block = {variant: [] for variant in binaries}
            for variant in order:
                elapsed, value = run(
                    binaries[variant], instance, level, replays)
                if value != reference_hash:
                    raise AssertionError("dispatcher result is not deterministic")
                samples[str(level)][variant].append(elapsed)
                block[variant].append(elapsed)
            paired_speedups[str(level)].append(
                statistics.mean(block["shared-counter"]) /
                statistics.mean(block["idle-parking"]))
    results = {}
    for level in levels:
        entry = {}
        for variant in binaries:
            values = samples[str(level)][variant]
            entry[variant] = {
                "median_ms": statistics.median(values)*1000,
                "min_ms": min(values)*1000,
                "max_ms": max(values)*1000,
                "samples_seconds": values,
            }
        block_speedups = paired_speedups[str(level)]
        entry["paired_speedups_over_shared_counter"] = block_speedups
        entry["speedup_over_shared_counter"] = statistics.median(
            block_speedups)
        entry["paired_relative_spread"] = (
            (max(block_speedups) - min(block_speedups)) /
            statistics.median(block_speedups))
        results[str(level)] = entry
    spreads = [
        (variant["max_ms"] - variant["min_ms"]) / variant["median_ms"]
        for entry in results.values()
        for variant in (entry["shared-counter"], entry["idle-parking"])
    ]
    serial = results["1"]
    serial_control_difference = abs(
        serial["idle-parking"]["median_ms"] -
        serial["shared-counter"]["median_ms"]
    ) / serial["shared-counter"]["median_ms"]
    paired_spread = max(
        entry["paired_relative_spread"] for entry in results.values())
    return {"description": WORKLOADS[workload]["description"],
            "result_dump_sha256": reference_hash, "levels": results,
            "maximum_relative_spread": max(spreads),
            "maximum_paired_relative_spread": paired_spread,
            "serial_control_difference": serial_control_difference,
            "measurement_valid": (paired_spread <= .15 and
                                  serial_control_difference <= .05)}


def benchmark(output, workloads, levels, repeats):
    output.mkdir(parents=True, exist_ok=False)
    load_average_before = os.getloadavg()
    results = {
        workload: measure(workload, output / workload, levels, repeats)
        for workload in workloads
    }
    report = {
        "schema": "b2-dispatcher-benchmark-v2",
        "measurement_started_at": datetime.now().astimezone().isoformat(),
        "environment": {"platform": platform.platform(),
                        "machine": platform.machine(),
                        "logical_cpus": os.cpu_count(),
                        "load_average_before": load_average_before,
                        "load_average_after": os.getloadavg()},
        "levels": levels, "repeats": repeats, "workloads": results,
        "measurement_valid": all(
            result["measurement_valid"] for result in results.values()),
    }
    (output / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    lines = ["# Idle-worker parking A/B", "",
             f"{repeats} alternating native replays after warm-up; result dumps "
             "are identical across variants and thread counts.", "",
             "| Workload | Threads | Shared counter (ms) | Idle parking (ms) | Speedup |",
             "| --- | ---: | ---: | ---: | ---: |"]
    for workload, result in results.items():
        for level in levels:
            entry = result["levels"][str(level)]
            lines.append(
                f"| {workload} | {level} | "
                f"{entry['shared-counter']['median_ms']:.3f} | "
                f"{entry['idle-parking']['median_ms']:.3f} | "
                f"{entry['speedup_over_shared_counter']:.2f}x |")
        if not result["measurement_valid"]:
            lines.append(
                f"\n{workload}: INVALID measurement (maximum paired spread "
                f"{result['maximum_paired_relative_spread']:.0%}; raw spread "
                f"{result['maximum_relative_spread']:.0%}; serial control "
                f"difference {result['serial_control_difference']:.0%}).")
    document = "\n".join(lines) + "\n"
    (output / "report.md").write_text(document)
    print(document, end="")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--workload", choices=WORKLOADS, action="append")
    parser.add_argument("--levels", type=parse_levels, default=[1, 2, 4, 8])
    parser.add_argument("--repeats", type=int, default=5)
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args()
    if not 1 <= args.repeats <= 20:
        parser.error("repeats must be within 1..20")
    report = benchmark(args.output.resolve(), args.workload or list(WORKLOADS),
                       args.levels, args.repeats)
    if args.strict and not report["measurement_valid"]:
        raise SystemExit("dispatcher benchmark was too noisy to accept")


if __name__ == "__main__":
    main()
