import hashlib
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from mam_deploy_confirmation_artifact import check_staged_source,recovery_gate
from mam_confirmation_identity import identity

class CacheTests(unittest.TestCase):
    def test_verified_existing_cache_and_source_are_allowed(self):
        with tempfile.TemporaryDirectory() as temp:
            p=Path(temp);(p/'a.py').write_text('x=1\n');cache=p/'__pycache__';cache.mkdir();raw=b'known generated bytecode';(cache/'a.cpython-312.pyc').write_bytes(raw)
            check_staged_source(p,{'a.py':'x=1\n'},{'a.cpython-312.pyc':hashlib.sha256(raw).hexdigest()})

    def test_unknown_or_changed_cache_is_rejected(self):
        with tempfile.TemporaryDirectory() as temp:
            p=Path(temp);(p/'a.py').write_text('x=1\n');cache=p/'__pycache__';cache.mkdir();(cache/'a.cpython-312.pyc').write_bytes(b'changed')
            for allowed in [{},{'a.cpython-312.pyc':'0'*64}]:
                with self.assertRaises(ValueError):check_staged_source(p,{'a.py':'x=1\n'},allowed)

    def test_source_drift_remains_rejected(self):
        with tempfile.TemporaryDirectory() as temp:
            p=Path(temp);(p/'a.py').write_text('changed')
            with self.assertRaises(ValueError):check_staged_source(p,{'a.py':'x=1\n'}, {})

    def test_only_original_completed_host_is_reused(self):
        e=Path(__file__).resolve().parents[1]/'mpi-evidence'
        prior=e/'confirmation-deployment-v1-seed1750';start=(prior/'intent.json').stat().st_mtime
        with patch('mam_deploy_confirmation_artifact.time.time',return_value=start+60):
            rows,previous,proof=recovery_gate(prior,identity(e))
        self.assertEqual([x['owned_ranks'] for x in rows],[list(range(8))])
        self.assertEqual(proof['remaining_private_collections'],3)
        self.assertEqual(proof['remaining_readbacks'],3)
        self.assertGreaterEqual(previous,51.947811291902326)

    def test_exhausted_shared_budget_rejected(self):
        e=Path(__file__).resolve().parents[1]/'mpi-evidence';prior=e/'confirmation-deployment-v1-seed1750'
        with patch('mam_deploy_confirmation_artifact.time.time',return_value=(prior/'intent.json').stat().st_mtime+721):
            with self.assertRaisesRegex(ValueError,'budget'):recovery_gate(prior,identity(e))

if __name__=='__main__':unittest.main()
